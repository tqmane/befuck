#!/usr/bin/env python3
"""Reproduce resource-independent Tabler paths. --fetch downloads only the pinned MIT sources."""
from pathlib import Path
import argparse
import json
import xml.etree.ElementTree as ET
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
PIN = 'bbed884d15354b5cebf2493371f20dc2d5e83eaf'  # Tabler 3.49.0
NAMES = 'x settings-2 adjustments-horizontal arrow-up-right chevron-right chevron-left map-pin photo video download search current-location trash check refresh rotate-clockwise crop player-play player-pause upload users globe shield-check info-circle alert-triangle plus camera camera-rotate list-search circle-check folder bolt file-text arrows-exchange circle-dashed calendar'.split()

def paths(svg):
    result = []
    for node in ET.fromstring(svg):
        tag = node.tag.split('}')[-1]
        a = node.attrib
        if a.get('stroke') == 'none':
            continue
        if tag == 'path':
            result.append(a['d'])
        elif tag == 'circle':
            x,y,r = (float(a[k]) for k in ('cx','cy','r'))
            result.append(f'M{x-r:g},{y:g}a{r:g},{r:g} 0 1,0 {2*r:g},0a{r:g},{r:g} 0 1,0 {-2*r:g},0')
        elif tag == 'line':
            result.append(f"M{a['x1']},{a['y1']}L{a['x2']},{a['y2']}")
        elif tag in ('polyline','polygon'):
            result.append('M' + a['points'] + ('z' if tag == 'polygon' else ''))
        elif tag == 'rect':
            x,y,w,h = (float(a.get(k,0)) for k in ('x','y','width','height'))
            rx=float(a.get('rx',0)); ry=float(a.get('ry',rx))
            result.append(f'M{x+rx:g},{y:g}h{w-2*rx:g}a{rx:g},{ry:g} 0 0,1 {rx:g},{ry:g}v{h-2*ry:g}a{rx:g},{ry:g} 0 0,1 {-rx:g},{ry:g}h{-w+2*rx:g}a{rx:g},{ry:g} 0 0,1 {-rx:g},{-ry:g}v{-h+2*ry:g}a{rx:g},{ry:g} 0 0,1 {rx:g},{-ry:g}z')
        else:
            raise ValueError(f'Unsupported SVG primitive {tag}')
    if not result:
        raise ValueError('Empty icon')
    return result

parser=argparse.ArgumentParser(); parser.add_argument('--fetch', action='store_true'); args=parser.parse_args()
source=ROOT/'third_party/tabler'; source.mkdir(parents=True, exist_ok=True)
if args.fetch:
    for name in ['LICENSE']+[n+'.svg' for n in NAMES]:
        relative = name if name == 'LICENSE' else 'icons/outline/'+name
        with urlopen(f'https://raw.githubusercontent.com/tabler/tabler-icons/{PIN}/{relative}', timeout=30) as response:
            (source/name).write_bytes(response.read())
entries=[]
for name in NAMES:
    entries.append('    '+name.upper().replace('-','_')+'(listOf('+', '.join(json.dumps(p) for p in paths((source/(name+'.svg')).read_text()))+'))')
text='''package dev.tqmane.befuck.ui

// Generated by checks/export_tabler.py from Tabler 3.49.0 (MIT).
// Upstream commit: '''+PIN+'''
internal enum class TablerIcon(val paths: List<String>) {
'''+',\n'.join(entries)+';\n}\n'
(ROOT/'app/src/main/kotlin/dev/tqmane/befuck/ui/TablerIcon.kt').write_text(text)
notice=ROOT/'THIRD_PARTY_NOTICES.md'
if notice.exists() and 'Tabler Icons' not in notice.read_text():
    notice.write_text(notice.read_text()+f'\n## Tabler Icons\n\nVersion 3.49.0, commit `{PIN}`. MIT License. Vendored sources and complete license: `third_party/tabler/`. Kotlin paths are mechanically converted, not substitutes.\n')
for name,file in [('plus','ic_befuck_add.xml'),('download','ic_befuck_download.xml')]:
    ps=paths((source/(name+'.svg')).read_text())
    vector='<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
    for p in ps:
        vector+='    <path android:pathData='+json.dumps(p)+' android:fillColor="@android:color/transparent" android:strokeColor="#FFFFFFFF" android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round" />\n'
    (ROOT/'app/src/main/res/drawable'/file).write_text(vector+'</vector>\n')
print(f'Generated {len(entries)} pinned Tabler icons')
